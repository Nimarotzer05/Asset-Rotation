"""Research round 4 (ADR 057/058): register the frozen data – the universe block and the strategy config – from the
pre-registered template, so that nothing is chosen by hand once the data is in the project. The template below is
part of the pre-registration: it states every number of ADR 057 (b)–(e) as amended by ADR 058.

Everything here was fixed before the download; only two inputs come from the data, both by rule:
    * the countries: every column of the frozen French file, in its order (ADR 057 a: "alle Länder der Datei");
    * the sample: the window rule of ADR 057 (f) as computed by scripts/allocator_v2_walkforward.py.

    python scripts/r4_register.py --sample 1977-01-31,2025-11-30 --write    # writes both files
    python scripts/r4_register.py --sample …                                  # --check: exit 1 if they differ

The static catalog's country tuple (rotationlab/data/providers/static.py, R4_COUNTRIES) must equal
`countries()`; tests/unit/test_r4_registration.py checks all three against this template.
"""

from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from rotationlab.data.providers.constructs_r4 import FX_SPOT, TREASURIES, country_slug  # noqa: E402

COUNTRY_FILE = os.path.join(ROOT, "data", "raw", "ff_intl_countries_monthly.csv.gz")
UNIVERSE = os.path.join(ROOT, "configs", "universe.yaml")
CONFIG = os.path.join(ROOT, "configs", "strategies", "sleeve_allocator_v2.yaml")
BEGIN = (
    "  # ---- research round 4 (ADR 057/058): generated by scripts/r4_register.py – do not edit by hand ----"
)
END = "  # ---- end of research round 4 ----"
INDUSTRIES = ("NoDur", "Durbl", "Manuf", "Enrgy", "HiTec", "Telcm", "Shops", "Hlth", "Utils", "Other")
COSTS = {
    "IND": 10.0,
    "CTRY": 20.0,
    "UST": 3.0,
    "FX": 3.0,
    "GOLD_D": 10.0,
    "SILVER": 15.0,
}  # ADR 057 (d), bp per side
CASH = "TBILL_IY"  # cash and financing leg: T-bill index on the investment yield (ADR 058 h)


def countries(path: str = COUNTRY_FILE) -> list[str]:
    cols = pd.read_csv(path, index_col=0, nrows=1).columns
    return [country_slug(str(c)) for c in cols]


def universe_block(ctry: list[str]) -> str:
    rows = [BEGIN]
    for i in INDUSTRIES:
        a = f"IND_{i.upper()}"
        rows.append(
            f'  {a}: {{ name: "US industry {i} (French, daily, value-weighted)", asset_class: equity, instrument: index, tradable: false, cost_bps: 0, series: {{ total_return: "static:r4:{a}" }} }}'
        )
    for c in ctry:
        a = f"CTRY_{c}"
        rows.append(
            f'  {a}: {{ name: "Country {c} (French, market with dividends, USD, monthly)", asset_class: equity, instrument: index, tradable: false, cost_bps: 0, series: {{ total_return: "static:r4:{a}" }} }}'
        )
    for a, (code, m) in TREASURIES.items():
        rows.append(
            f'  {a}: {{ name: "{m:.0f}y Treasury par bond (daily, {code})", asset_class: bond, instrument: index, tradable: false, cost_bps: 0, series: {{ total_return: "static:r4:{a}" }} }}'
        )
    for f in FX_SPOT:
        a = f"FX_{f}"
        rows.append(
            f'  {a}: {{ name: "{f} deposit in USD (H.10 spot, OECD short rate)", asset_class: currency, instrument: index, tradable: false, cost_bps: 0, series: {{ total_return: "static:r4:{a}" }} }}'
        )
    rows.append(END)
    return "\n".join(rows) + "\n"


def strategy_yaml(ctry: list[str], sample: tuple[str, str]) -> str:
    ind = [f"IND_{i.upper()}" for i in INDUSTRIES]
    cty = [f"CTRY_{c}" for c in ctry]
    ust = list(TREASURIES)
    fx = [f"FX_{f}" for f in FX_SPOT]
    uni = f"[{', '.join([*ind, *cty, *ust, *fx, 'GOLD_D', 'SILVER', CASH])}]"
    spec = "\n".join(
        f'        FX_{f}: {{ kind: yield, series: "static:r4:RATE_{f}", max_age_months: 3 }}' for f in FX_SPOT
    )
    cost_rows = [
        *(f"      {a}: {COSTS['IND']}" for a in ind),
        *(f"      {a}: {COSTS['CTRY']}" for a in cty),
        *(f"      {a}: {COSTS['UST']}" for a in ust),
        *(f"      {a}: {COSTS['FX']}" for a in fx),
        f"      GOLD_D: {COSTS['GOLD_D']}",
        f"      SILVER: {COSTS['SILVER']}",
        f"      {CASH}: 0.0",
    ]
    return f"""# GENERATED by scripts/r4_register.py from the pre-registered template (ADR 057/058) – do not edit by hand
id: sleeve_allocator_v2
version: 1
role: paper                        # research round 4 (ADR 057): outside the risk budgets, no capital
cadence: monthly
# research instruments only (ADR 057 a); a live mapping exists only after the primary criterion is met, in its own ADR
universe: {uni}
long_history_universe: {uni}
warmup_months: 30
params:
  cash: {CASH}                   # T-bill index on the investment yield (ADR 058 h)
  # every number below is fixed by ADR 057/058 before the data was downloaded; nothing is chosen on the data
  sleeves:
    EQ_US:   {{ instruments: [{", ".join(ind)}], mode: long_xs, families: {{ mom_12_1: 1.0 }}, vol: daily, budget: 0.125, group: physical }}
    EQ_INTL: {{ instruments: [{", ".join(cty)}], mode: long_xs, families: {{ mom_12_1: 1.0 }}, vol: monthly, budget: 0.125, group: physical }}
    FI:      {{ instruments: [{", ".join(ust)}], mode: long_ts, vol: daily, budget: 0.25, group: rates }}
    FX:      {{ instruments: [{", ".join(fx)}], mode: long_short_xs, families: {{ carry_yield: 1.0, mom_12_1: 1.0 }}, vol: daily, budget: 0.25, group: overlay }}
    PM:      {{ instruments: [GOLD_D, SILVER], mode: long_ts, vol: daily, budget: 0.25, group: physical }}
  min_instruments: {{ long_xs: 6, long_ts: 1, long_short_xs: 6 }}
  feature_params:
    carry_yield:
      spec:
{spec}
  zscore_clip: 3.0
  xs_select: true                  # rank portfolios in the cross-sectional sleeves (ADR 057 c)
  ts_filter: true                  # 12-month excess return over cash > 0 in the long sleeves (ADR 057 c)
  vol_daily: {{ com: 60, min_obs: 120, floor: 0.02, stale_days: 10 }}
  vol_monthly: {{ half_life: 12, min_obs: 24, floor: 0.02 }}
  correlation: {{ half_life: 24, min_obs: 24, floor: 0.02 }}
  vol_target: 0.10
  caps: {{ physical: 1.0, physical_plus_rates: 1.5, overlay_gross: 0.5 }}
  band: 0.0
confidence:
  kind: score_dispersion
  floor: 0.5
  params: {{ scale: 1.0 }}
golden_run:
  data_from: 1971-01-31            # panel from the first H.10 quotes (ADR 058)
  start: 1971-01-31
  end: 2026-09-30
  sample: [{sample[0]}, {sample[1]}]   # the window rule of ADR 057 (f); the walk-forward refuses any other value
  count_warmup: false
  execution: next_tradable
  costs:
    default_bps: null              # per-instrument rates (ADR 057 d), cash leg free
    cash_bps: 0.0
    borrow_bps: {{ CASH: 30.0 }}     # negative cash financed at the T-bill index + 30 bp p.a. (ADR 057 d)
    per_asset:
{chr(10).join(cost_rows)}
"""


def universe_with_block(text: str, block: str) -> str:
    """configs/universe.yaml with the generated block (replaced if present, else before the ETF universe)."""
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END + "\n", 1)
        return head + block + tail
    anchor = "  # ---- tradable ETF universe (live), mapped to long-history proxies ----"
    if anchor not in text:
        raise ValueError("configs/universe.yaml: anchor of the ETF universe not found")
    return text.replace(anchor, block + "\n" + anchor, 1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sample", required=True, help="first,last return month (window rule, ADR 057 f)")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    s0, s1 = a.sample.split(",")
    ctry = countries()
    uni_now = open(UNIVERSE, encoding="utf-8").read()
    uni_new = universe_with_block(uni_now, universe_block(ctry))
    cfg_new = strategy_yaml(ctry, (s0, s1))
    if a.write:
        with open(UNIVERSE, "w", encoding="utf-8") as fh:
            fh.write(uni_new)
        with open(CONFIG, "w", encoding="utf-8") as fh:
            fh.write(cfg_new)
        print(f"written: {len(ctry)} countries, sample {s0} … {s1}")
        return 0
    cfg_now = open(CONFIG, encoding="utf-8").read() if os.path.exists(CONFIG) else ""
    same = uni_now == uni_new and cfg_now == cfg_new
    print("registration equals the template" if same else "registration DIFFERS from the template")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
