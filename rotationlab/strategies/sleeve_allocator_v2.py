"""Sleeve allocator v2 (ADR 057, precised by ADR 058 before the data): breadth across five sleeves, the weaknesses of
round 3 fixed.

Sleeve modes
    long_xs        long-only cross-section (US industries, country indices): the long leg of the rank
                   portfolio of Asness/Moskowitz/Pedersen (2013) – weight ∝ max(rank offset, 0) / σ – over
                   the instruments available at D; with `xs_select` off: inverse volatility over all of them
    long_ts        long-only, time series only (Treasuries, precious metals): inverse volatility
    long_short_xs  dollar-neutral cross-section (currencies): weight ∝ rank offset in notional, Σ|w| = 1;
                   inactive with `xs_select` off (a long-short sleeve has no passive version)
    rank offset    (N+1)/2 − rank, rank 1 = highest score; scores equal to 1e-12 tie and the instrument earlier
                   in the configuration ranks higher (as in round 3)

Steps at a decision date D
    1. availability  an instrument belongs to its sleeve's cross-section at D iff every input exists: 12-1
                     momentum, 12-month excess return over cash, its weighting volatility, a monthly EWMA
                     volatility (≥ 24 monthly returns, so every basket has a joint history) and – in sleeves
                     with carry – the carry yield. The rule does not depend on the signal switches, so the
                     baselines see exactly the same instruments. A sleeve without budget is switched off.
    2. activity      a sleeve is active with at least `min_instruments[mode]` available instruments; a sleeve
                     may list no instrument at all (ADR 057 h: never active)
    3. baskets       per mode as above; scores are equal-weighted, clipped z-scores of the sleeve's families
    4. risk parity   a_s = budget_s / σ_s, σ_s = EWMA volatility of today's unfiltered basket: its daily
                     returns (centre of mass 60 sessions) in `vol: daily` sleeves, its monthly returns
                     (half-life 12) in `vol: monthly` sleeves
    5. vol target    k = vol_target / σ_book with σ_book = √(a'DRDa + idle) of the unfiltered *long* book (groups
                     `physical` and `rates`): D the sleeve volatilities of step 4, R the EWMA correlation of the
                     baskets' monthly returns (half-life 24 months) – volatilities fast, correlations slow; `idle`
                     = Σ budget² of long sleeves with a budget that are inactive at D, so their budget stays in
                     cash instead of going to the others (ADR 058 d). The currency overlay is sized with the same
                     k (a = budget/σ) but does not enter σ_book: the long book – and the passive baseline B1 –
                     are sized identically with or without the overlay (ADR 058 d). Only when no long sleeve has
                     a budget (the variant "overlay alone") is the target set on the overlay itself; when long
                     sleeves have budgets but none is active yet, there is no proposal (warm-up).
    6. caps          on the unfiltered book (where k is set): physical sleeves (group `physical`: equities,
                     metals) ≤ caps.physical of NAV; physical + rates ≤ caps.physical_plus_rates (bond leverage);
                     overlay Σ|w| ≤ caps.overlay_gross; together never above the system's gross limit of 2.0. A
                     binding cap scales the sleeves it governs down by one factor; the book then runs below its
                     target (ADR 058 a/finding 1: caps before the filter, so the filter never refills a cap)
    7. trend filter  an instrument of a long sleeve with 12-month excess return ≤ 0 gets weight 0: its share
                     stays in cash, nothing is re-scaled (the filter lowers risk)
    8. band          an instrument moves only when its target changes by at least `band` (0 = rebalance every
                     month, the ADR 057 setting); a zero target always trades; caps re-checked

Instrument volatility: EWMA of daily returns (centre of mass 60 sessions, Moskowitz/Ooi/Pedersen 2012) for
`vol: daily` sleeves, EWMA of monthly returns (half-life 12) for `vol: monthly` sleeves. Every number is fixed
in configs/strategies/sleeve_allocator_v2.yaml (generated by scripts/r4_register.py from the template of ADR
057/058) before the first run; nothing adapts to the data.
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

import numpy as np
import pandas as pd

from rotationlab.core import registry
from rotationlab.core.errors import ConfigError
from rotationlab.core.protocols import MarketView
from rotationlab.core.types import AssetId, Proposal, StrategyState
from rotationlab.strategies.base import BaseStrategy, weighted_composite, zscore

FAMILIES = ("mom_12_1", "carry_yield")
MODES = ("long_xs", "long_ts", "long_short_xs")
GROUPS = ("physical", "rates", "overlay")
MIN_INSTRUMENTS = {"long_xs": 6, "long_ts": 1, "long_short_xs": 6}
GROSS_LIMIT = 2.0  # the system's limit on a proposal's gross exposure (rotationlab.core.types.Proposal)


@dataclass(frozen=True)
class SleeveV2:
    name: str
    instruments: tuple[str, ...]
    mode: str
    families: Mapping[str, float]
    vol: str
    budget: float
    group: str


TIE_DECIMALS = 12  # scores equal to 1e-12 are a tie; float residues never decide (ADR 056, finding 1)


def rank_offsets(score: pd.Series) -> pd.Series:
    """(N+1)/2 − rank with rank 1 = highest score; on a tie (1e-12) the instrument earlier in the configuration
    ranks higher, as in round 3 (ADR 058)."""
    r = score.round(TIE_DECIMALS).rank(ascending=False, method="first")
    return (len(score) + 1) / 2.0 - r


def long_leg_weights(score: pd.Series, vol: pd.Series) -> pd.Series:
    """Long leg of the rank portfolio, risk-scaled: ∝ max(rank − (N+1)/2, 0) / σ, normalised to one."""
    v = rank_offsets(score).clip(lower=0.0) / vol.reindex(score.index)
    v = v[v > 0]
    return v / v.sum()


def long_short_weights(score: pd.Series) -> pd.Series:
    """Dollar-neutral rank portfolio in notional: ∝ rank − (N+1)/2, Σ|w| = 1."""
    v = rank_offsets(score)
    gross = v.abs().sum()
    return v / gross if gross > 0 else v * 0.0


def inverse_vol(vol: pd.Series) -> pd.Series:
    inv = 1.0 / vol
    return inv / inv.sum()


@registry.strategy
class SleeveAllocatorV2(BaseStrategy):
    strategy_id = "sleeve_allocator_v2"

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        p = self.params
        self.sleeves = [self._sleeve(name, dict(cfg)) for name, cfg in dict(p["sleeves"]).items()]
        listed = [a for s in self.sleeves for a in s.instruments]
        if len(set(listed)) != len(listed):
            raise ValueError("sleeve_allocator_v2: an instrument belongs to more than one sleeve")
        if set(listed) != {str(a) for a in self.assets}:
            raise ValueError("sleeve_allocator_v2: the sleeves must cover exactly the universe without cash")
        if sum(s.budget for s in self.sleeves) <= 0:
            raise ValueError("sleeve_allocator_v2: at least one sleeve needs a positive budget")
        self.min_instruments = {
            **MIN_INSTRUMENTS,
            **{str(k): int(v) for k, v in dict(p.get("min_instruments", {})).items()},
        }
        self.feature_params = {k: dict(v) for k, v in dict(p.get("feature_params", {})).items()}
        self.clip = float(p.get("zscore_clip", 3.0))
        self.xs_select = bool(p.get("xs_select", True))
        self.ts_filter = bool(p.get("ts_filter", True))
        self.vol_daily = {
            "com": 60,
            "min_obs": 120,
            "floor": 0.02,
            "stale_days": 10,
            **dict(p.get("vol_daily", {})),
        }
        self.vol_monthly = {"half_life": 12, "min_obs": 24, "floor": 0.02, **dict(p.get("vol_monthly", {}))}
        self.corr = {"half_life": 24, "min_obs": 24, "floor": 0.02, **dict(p.get("correlation", {}))}
        self.vol_target = float(p.get("vol_target", 0.10))
        caps = {"physical": 1.0, "physical_plus_rates": 1.5, "overlay_gross": 0.5, **dict(p.get("caps", {}))}
        self.caps = {k: float(v) for k, v in caps.items()}
        self.band = float(p.get("band", 0.0))
        if self.vol_target <= 0 or min(self.caps.values()) <= 0 or self.band < 0:
            raise ValueError("sleeve_allocator_v2: vol_target and caps must be positive, band ≥ 0")
        if self.caps["physical_plus_rates"] < self.caps["physical"]:
            raise ValueError("sleeve_allocator_v2: caps.physical_plus_rates must be ≥ caps.physical")
        if self.caps["physical_plus_rates"] + self.caps["overlay_gross"] > GROSS_LIMIT + 1e-12:
            raise ValueError(
                f"sleeve_allocator_v2: caps allow a gross exposure above the system limit {GROSS_LIMIT} (Proposal)"
            )
        self._daily_ok: set[str] = set()

    @staticmethod
    def _sleeve(name: str, cfg: dict[str, Any]) -> SleeveV2:
        mode, group, vol = str(cfg["mode"]), str(cfg["group"]), str(cfg.get("vol", "daily"))
        fam = {str(k): float(v) for k, v in dict(cfg.get("families", {})).items()}
        if mode not in MODES or group not in GROUPS or vol not in ("daily", "monthly"):
            raise ValueError(f"sleeve_allocator_v2: sleeve {name}: mode {mode}, group {group}, vol {vol}")
        if set(fam) - set(FAMILIES):
            raise ValueError(
                f"sleeve_allocator_v2: sleeve {name}: unsupported families {sorted(set(fam) - set(FAMILIES))}"
            )
        if mode != "long_ts" and not fam:
            raise ValueError(f"sleeve_allocator_v2: sleeve {name}: a cross-sectional sleeve needs families")
        if mode == "long_short_xs" and group != "overlay":
            raise ValueError(
                f"sleeve_allocator_v2: sleeve {name}: a long-short sleeve belongs to the overlay"
            )
        budget = float(cfg["budget"])
        if budget < 0:
            raise ValueError(f"sleeve_allocator_v2: sleeve {name}: negative budget")
        instruments = tuple(str(a) for a in cfg["instruments"])  # may be empty: never active (ADR 057 h)
        return SleeveV2(name, instruments, mode, fam, vol, budget, group)

    # -- inputs --------------------------------------------------------------------
    def _check_daily(self, s: SleeveV2, view: MarketView) -> None:
        """A `vol: daily` sleeve must hold instruments with daily prices (a monthly series would be annualised
        with √252 – a configuration error, raised once per instrument)."""
        todo = [a for a in s.instruments if a not in self._daily_ok]
        if not todo:
            return
        tr = view.total_return(todo, None)
        for a in todo:
            idx = tr[a].dropna().index if a in tr.columns else pd.DatetimeIndex([])
            if len(idx) < 12:
                continue  # too little history to tell; checked again at the next decision
            gap = float(pd.Series(idx[-40:]).diff().dt.days.median())
            if gap > 7:
                raise ConfigError(
                    f"sleeve {s.name}: vol daily, but {a} has a median spacing of {gap:.0f} days"
                )
            self._daily_ok.add(a)

    def _inputs(self, s: SleeveV2, view: MarketView) -> pd.DataFrame:
        """One row per instrument: mom_12_1, excess12, vol (weighting), vol_m (monthly), carry (if used)."""
        a = list(s.instruments)
        if s.vol == "daily":
            self._check_daily(s, view)
        cols = {
            "mom_12_1": self.feature("mom_12_1", view, a),
            "excess12": self.feature("excess_mom_12m", view, a, cash=str(self.cash)),
            "vol_m": self.feature("vol_ewma", view, a, **self.vol_monthly),
        }
        if s.vol == "daily":
            cols["vol"] = self.feature("vol_ewma_d", view, a, **self.vol_daily)
        else:
            cols["vol"] = cols["vol_m"]
        if "carry_yield" in s.families:
            cols["carry_yield"] = self.feature(
                "carry_yield", view, a, **self.feature_params.get("carry_yield", {})
            )
        return pd.DataFrame(cols).reindex(a)

    def _score(self, s: SleeveV2, x: pd.DataFrame) -> pd.Series:
        """Equal-weighted, clipped z-scores of the sleeve's families over its available instruments."""
        z = {k: zscore(x[k], self.clip) for k in s.families}
        return weighted_composite(z, s.families).reindex(x.index)

    def _basket(self, s: SleeveV2, x: pd.DataFrame, score: pd.Series | None) -> pd.Series:
        """Unfiltered weights over the available instruments (empty = the sleeve is inactive)."""
        if s.mode == "long_ts" or (s.mode == "long_xs" and not self.xs_select):
            return inverse_vol(x["vol"])
        if s.mode == "long_short_xs" and not self.xs_select:
            return pd.Series(dtype=float)
        if score is None or score.isna().any():
            return pd.Series(dtype=float)
        if s.mode == "long_xs":
            return long_leg_weights(score, x["vol"])
        return long_short_weights(score)

    def _basket_vol(self, s: SleeveV2, view: MarketView, w: Mapping[str, float]) -> float:
        if s.vol == "daily":
            return float(self.feature("basket_vol_ewma_d", view, None, weights=dict(w), **self.vol_daily))
        return float(self.feature("basket_vol_ewma", view, None, weights=dict(w), **self.vol_monthly))

    def _book_vol(
        self,
        view: MarketView,
        baskets: Mapping[str, pd.Series],
        sizes: Mapping[str, float],
        vols: Mapping[str, float],
        idle: float = 0.0,
    ) -> float:
        b = {n: {str(a): float(x) for a, x in w.items()} for n, w in baskets.items()}
        return float(
            self.feature(
                "book_vol_hybrid",
                view,
                None,
                baskets=b,
                sizes=dict(sizes),
                vols=dict(vols),
                idle=float(idle),
                **self.corr,
            )
        )

    # -- the decision ---------------------------------------------------------------
    def propose(self, view: MarketView, state: StrategyState) -> tuple[Proposal, StrategyState]:
        signals: dict[str, float] = {}
        notes: list[str] = []
        full: dict[str, pd.Series] = {}  # unfiltered baskets of the active sleeves
        avail_of: dict[str, pd.DataFrame] = {}
        size: dict[str, float] = {}
        vol_s: dict[str, float] = {}
        idle = 0.0  # Σ budget² of long sleeves that have a budget but are inactive (ADR 058 d)
        for s in self.sleeves:
            if s.budget <= 0:  # a sleeve without budget is switched off: no inputs, no signals
                continue
            basket, sig, avail = self._sleeve_now(s, view, signals)
            signals[f"active:{s.name}"] = 0.0 if basket is None else 1.0
            if basket is None:
                if s.group != "overlay":
                    idle += s.budget**2
                continue
            full[s.name] = basket
            avail_of[s.name] = avail
            size[s.name] = s.budget / sig
            vol_s[s.name] = sig
            signals[f"sleeve_vol:{s.name}"] = sig
        signals["sleeves_active"] = float(len(full))
        signals["idle_budget"] = float(np.sqrt(idle))
        by_name = {s.name: s for s in self.sleeves}
        long_budget = any(s.budget > 0 and s.group != "overlay" for s in self.sleeves)
        base = [n for n in full if by_name[n].group != "overlay"] if long_budget else list(full)
        if not base:
            why = (
                "no long sleeve has enough instruments with complete inputs"
                if long_budget
                else "no active sleeve"
            )
            return self.warmup_proposal(view, why), state
        sig_book = self._book_vol(
            view,
            {n: full[n] for n in base},
            {n: size[n] for n in base},
            {n: vol_s[n] for n in base},
            idle if long_budget else 0.0,
        )
        if not math.isfinite(sig_book) or sig_book <= 0:
            return self.warmup_proposal(view, "no volatility of the book yet"), state
        k = self.vol_target / sig_book
        signals["book_vol_unfiltered"] = sig_book
        signals["k"] = k
        unfiltered = {n: b * size[n] * k for n, b in full.items()}
        factor = self._cap_factors(unfiltered, signals, notes)
        capped = {n: b * factor[by_name[n].group] for n, b in unfiltered.items()}
        signals.update(
            {f"pre_filter_{k_}": v for k_, v in self._group_sums(capped).items()}
        )  # constructed mix
        weights = self._filtered(capped, avail_of, notes)
        g = self._group_sums(weights)
        signals.update({f"gross_{k_}": v for k_, v in g.items()})
        for n, b in weights.items():
            signals[f"sleeve_weight:{n}"] = (
                float(b.abs().sum()) if by_name[n].group == "overlay" else float(b.sum())
            )
        signals["book_vol_predicted"] = self._predicted(view, weights)
        targets = {str(a): float(x) for b in weights.values() for a, x in b.items() if abs(x) > 1e-12}
        return self._banded(view, targets, signals, notes, state)

    def _filtered(
        self, capped: Mapping[str, pd.Series], avail_of: Mapping[str, pd.DataFrame], notes: list[str]
    ) -> dict[str, pd.Series]:
        """Step 7: in the long sleeves an instrument with 12-month excess return ≤ 0 goes to cash (weight 0);
        nothing else changes."""
        by_name = {s.name: s for s in self.sleeves}
        weights: dict[str, pd.Series] = {}
        for n, w in capped.items():
            if not self.ts_filter or by_name[n].mode == "long_short_xs":
                weights[n] = w
                continue
            keep = avail_of[n]["excess12"].reindex(w.index) > 0
            out = [a for a in w.index if not bool(keep[a])]
            if out:
                notes.append(f"{n}: 12-month excess return ≤ 0, in cash: {', '.join(out)}")
            weights[n] = w.where(keep, 0.0)
        return weights

    def _sleeve_now(
        self, s: SleeveV2, view: MarketView, signals: dict[str, float]
    ) -> tuple[pd.Series | None, float, pd.DataFrame]:
        """The sleeve's unfiltered basket, its volatility and the available inputs at D (None if inactive)."""
        if not s.instruments:
            signals[f"available:{s.name}"] = 0.0
            return None, math.nan, pd.DataFrame()
        x = self._inputs(s, view)
        avail = x.dropna()
        signals[f"available:{s.name}"] = float(len(avail))
        if len(avail) < self.min_instruments[s.mode]:
            return None, math.nan, avail
        score = self._score(s, avail) if s.families else None
        if score is not None:  # recorded for the per-sleeve evaluation, with or without selection
            signals.update({f"score:{a}": float(v) for a, v in score.items()})
        b = self._basket(s, avail, score)
        if b.empty:
            return None, math.nan, avail
        sig = self._basket_vol(s, view, {str(a): float(x) for a, x in b.items()})
        if not math.isfinite(sig):
            return None, math.nan, avail
        return b, sig, avail

    def _predicted(self, view: MarketView, weights: Mapping[str, pd.Series]) -> float:
        """Predicted volatility of the book actually proposed (after filter and caps): every sleeve's own
        weights are its basket (size 1), so the prediction is comparable with the realised volatility."""
        by_name = {s.name: s for s in self.sleeves}
        held = {n: b[b.abs() > 1e-12] for n, b in weights.items()}
        held = {n: b for n, b in held.items() if len(b)}
        if not held:
            return 0.0
        vols = {
            n: self._basket_vol(by_name[n], view, {str(a): float(x) for a, x in b.items()})
            for n, b in held.items()
        }
        if not all(math.isfinite(v) for v in vols.values()):
            return float("nan")
        return self._book_vol(view, held, dict.fromkeys(held, 1.0), vols)

    def _cap_factors(
        self, unfiltered: Mapping[str, pd.Series], signals: dict[str, float], notes: list[str]
    ) -> dict[str, float]:
        """Scale factors per group from the *unfiltered* book (ADR 058, finding 1): physical first, then the room
        the physical sleeves leave under the bond-leverage cap, then the overlay. The filter applied afterwards
        only moves shares to cash, so it can never free room that another sleeve would fill."""
        g = self._group_sums(unfiltered)
        cap_p, cap_pr, cap_o = (
            self.caps["physical"],
            self.caps["physical_plus_rates"],
            self.caps["overlay_gross"],
        )
        f = {"physical": 1.0, "rates": 1.0, "overlay": 1.0}
        signals["cap_physical"] = signals["cap_rates"] = signals["cap_overlay"] = 0.0
        if g["physical"] > cap_p:
            f["physical"] = cap_p / g["physical"]
            signals["cap_physical"] = 1.0
            notes.append(f"physical sleeves {g['physical']:.2f} > {cap_p:.2f}: scaled down")
        room = max(cap_pr - g["physical"] * f["physical"], 0.0)
        if g["rates"] > room:
            f["rates"] = room / g["rates"] if g["rates"] > 0 else 0.0
            signals["cap_rates"] = 1.0
            notes.append(
                f"rates sleeve {g['rates']:.2f} > room {room:.2f} under the {cap_pr:.2f} cap: scaled down"
            )
        if g["overlay"] > cap_o:
            f["overlay"] = cap_o / g["overlay"]
            signals["cap_overlay"] = 1.0
            notes.append(f"currency overlay gross {g['overlay']:.2f} > {cap_o:.2f}: scaled down")
        return f

    def _group_sums(self, weights: Mapping[str, pd.Series]) -> dict[str, float]:
        g = {"physical": 0.0, "rates": 0.0, "overlay": 0.0}
        by_name = {s.name: s for s in self.sleeves}
        for n, b in weights.items():
            grp = by_name[n].group
            g[grp] += float(b.abs().sum()) if grp == "overlay" else float(b.sum())
        return g

    def _capped(self, weights: dict[str, pd.Series], notes: list[str]) -> dict[str, pd.Series]:
        """The caps on a given book (after the band): the same factors applied to it."""
        f = self._cap_factors(weights, {}, notes)
        by_name = {s.name: s for s in self.sleeves}
        return {n: b * f[by_name[n].group] for n, b in weights.items()}

    def _banded(
        self,
        view: MarketView,
        targets: Mapping[str, float],
        signals: dict[str, float],
        notes: list[str],
        state: StrategyState,
    ) -> tuple[Proposal, StrategyState]:
        """Keep the last target where the new one is within `band`; then re-check the caps."""
        last = {str(k): float(v) for k, v in dict(state.extra.get("targets", {})).items()}
        final: dict[str, float] = {}
        held = 0
        for a in sorted(set(targets) | set(last)):
            t, prev = float(targets.get(a, 0.0)), float(last.get(a, 0.0))
            if a in last and a in targets and abs(t - prev) < self.band:  # an exit (target 0) always trades
                final[a] = prev
                held += 1
            else:
                final[a] = t
        if held:
            notes.append(f"{held} target(s) within the {self.band:.0%} band kept at the last target")
        grouped = self._as_sleeves(final)
        recheck: list[str] = []
        capped = self._capped(grouped, recheck)
        if recheck:
            notes.append("after the band: " + "; ".join(recheck))
        final = {str(a): float(x) for b in capped.values() for a, x in b.items() if abs(x) > 1e-12}
        signals["gross"] = float(sum(abs(v) for v in final.values()))
        signals["net_long"] = float(sum(final.values()))
        new_state = StrategyState(
            state.strategy_id,
            positions={AssetId(a): w for a, w in final.items()},
            entries=state.entries,
            extra={"targets": dict(final)},
        )
        strength = min(1.0, signals["gross"] / max(self.caps["physical_plus_rates"], 1e-9))
        return self.proposal(view, final, strength, signals, tuple(notes)), new_state

    def _as_sleeves(self, w: Mapping[str, float]) -> dict[str, pd.Series]:
        out: dict[str, pd.Series] = {}
        for s in self.sleeves:
            vals = {a: w[a] for a in s.instruments if a in w}
            if vals:
                out[s.name] = pd.Series(vals, dtype=float)
        return out


